// node tools/savestate-v1-fixtures.ts [--write]
// Version 1 save-state fixtures: one per shipped ROM (roms/manifest.json entries outside
// conformance/), in tests/fixtures/savestate-v1/<rom>.v1.state, with index.json recording how each
// was made and its Machine.hash(). Each is a power-on machine run for FRAMES frames of a
// deterministic replay prefix: the first FRAMES frames of replays/<rom>.replay.json when the ROM
// has one, otherwise no input. The bytes are Machine.saveStateV1(), the layout every save written
// before save states v2 used (docs/spec-notes.md "Save-state format").
//
// The fixtures stand for storage written before v2, so they are frozen: --write adds fixtures for
// ROMs that have none and never rewrites an existing one. Without --write the tool only reports.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { Machine } from "../src/machine/machine.ts";
import { Tally } from "../src/machine/cpu.ts";
import { buildOne, discoverRoms } from "./build-roms.ts";
import { padsFromEntries, type ReplayFile } from "./replay.ts";

export const FIXTURE_DIR = "tests/fixtures/savestate-v1";
export const FRAMES = 120;

export type FixtureEntry = { romSha256: string; frames: number; input: string; hash: string };
export type FixtureIndex = { note: string; states: Record<string, FixtureEntry> };

const NOTE = "Generated by `node tools/savestate-v1-fixtures.ts --write`. Frozen v1 save states (storage written before save states v2); never edit or regenerate by hand.";

/** Manifest ROMs a player can own: everything outside conformance/. */
export function shippedRoms(manifest = "roms/manifest.json"): string[] {
  const roms = JSON.parse(readFileSync(manifest, "utf8")).roms as Record<string, unknown>;
  return Object.keys(roms).filter(n => !n.startsWith("conformance/")).sort();
}

export function fixtureIndex(dir = FIXTURE_DIR): FixtureIndex {
  const f = `${dir}/index.json`;
  return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) as FixtureIndex : { note: NOTE, states: {} };
}

/** Run `name` from power-on for FRAMES frames of its replay prefix; return the v1 bytes and entry. */
export function makeFixture(name: string): { bytes: Uint8Array; entry: FixtureEntry } {
  const src = discoverRoms().find(s => s.name === name);
  if (!src) throw new Error(`no ROM source for ${name}`);
  const rom = buildOne(src);
  const replayFile = `replays/${name}.replay.json`;
  let pads = (_f: number): [number, number] => [0, 0], input = "no input";
  if (existsSync(replayFile)) {
    const r = JSON.parse(readFileSync(replayFile, "utf8")) as ReplayFile;
    pads = padsFromEntries(r.pads);
    input = `first ${FRAMES} frames of ${replayFile}`;
  }
  const m = new Machine(rom, { cpu: new Tally() });
  for (let f = 0; f < FRAMES; f++) { const [a, b] = pads(f); m.runFrame(a, b); }
  return { bytes: m.saveStateV1(), entry: { romSha256: m.romSha256, frames: FRAMES, input, hash: m.hash() } };
}

if (/(^|[\\/])savestate-v1-fixtures\.ts$/.test(process.argv[1] ?? "")) {
  const write = process.argv.includes("--write");
  const index = fixtureIndex();
  let added = 0;
  for (const name of shippedRoms()) {
    if (index.states[name] && existsSync(`${FIXTURE_DIR}/${name}.v1.state`)) { console.log(`kept   ${name.padEnd(16)} hash=${index.states[name].hash} (frozen)`); continue; }
    const { bytes, entry } = makeFixture(name);
    console.log(`${write ? "wrote " : "would write"} ${name.padEnd(16)} hash=${entry.hash} ${bytes.length} bytes (${entry.input})`);
    if (!write) continue;
    mkdirSync(FIXTURE_DIR, { recursive: true });
    writeFileSync(`${FIXTURE_DIR}/${name}.v1.state`, bytes);
    index.states[name] = entry;
    added++;
  }
  if (write && added) {
    const states = Object.fromEntries(Object.keys(index.states).sort().map(k => [k, index.states[k]]));
    writeFileSync(`${FIXTURE_DIR}/index.json`, JSON.stringify({ note: NOTE, states }, null, 2) + "\n");
  }
}
