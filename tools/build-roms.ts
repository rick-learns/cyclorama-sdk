// npm run build:roms [-- --write-manifest]
// Builds every ROM in the project from source with the project's own toolchain:
//   roms/<name>/<name>.asm  (CYASM)   or   roms/<name>/<name>.scr  (SCRIM, compiled to CYASM)
//   tests/conformance/*.asm (conformance ROMs; files starting with "_" are includes)
// Output: build/roms/<name>.rom. roms/manifest.json records each ROM's size and SHA-256;
// the build is a pure function of the sources, so the manifest is checked by tests.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { assemble } from "../src/asm/assembler.ts";
import { sourceReader } from "./art.ts";
import { compile as scrimCompile } from "../src/scrim/compile.ts";
import { isCliEntry } from "./cli-entry.ts";

export type RomSource = { name: string; file: string; lang: "asm" | "scrim" };

export const sha256 = (b: Uint8Array) => createHash("sha256").update(b).digest("hex");

export function discoverRoms(): RomSource[] {
  const out: RomSource[] = [];
  for (const d of readdirSync("roms").sort()) {
    const dir = join("roms", d);
    if (!statSync(dir).isDirectory()) continue;
    for (const [ext, lang] of [["scr", "scrim"], ["asm", "asm"]] as const) {
      const f = join(dir, `${d}.${ext}`);
      if (existsSync(f)) { out.push({ name: d, file: f, lang }); break; }
    }
  }
  for (const f of readdirSync("tests/conformance").sort())
    if (f.endsWith(".asm") && !f.startsWith("_")) out.push({ name: `conformance/${f.slice(0, -4)}`, file: join("tests/conformance", f), lang: "asm" });
  return out;
}

const readSource = sourceReader((p: string): string | Uint8Array => (/\.(asm|inc|scr|txt|art|song)$/i.test(p) ? readFileSync(p, "utf8") : new Uint8Array(readFileSync(p))));

/** Kept for callers written before the compiler existed; the compiler is now imported statically. */
export async function loadScrim() {}

export function buildOne(src: RomSource): Uint8Array {
  if (src.lang === "asm") {
    const r = assemble(src.file, readSource);
    if (r.errors.length) throw new Error(`${src.name}:\n` + r.errors.map(e => `  ${e.file}:${e.line}: ${e.message}`).join("\n"));
    return r.rom;
  }
  const r = scrimCompile(src.file, readSource);
  if (r.errors.length || !r.rom) throw new Error(`${src.name}:\n` + r.errors.map(e => `  ${e.file}:${e.line}: ${e.message}`).join("\n"));
  return r.rom;
}

export function buildAll(): Record<string, Uint8Array> {
  const out: Record<string, Uint8Array> = {};
  for (const s of discoverRoms()) out[s.name] = buildOne(s);
  return out;
}

export function manifestOf(roms: Record<string, Uint8Array>) {
  const sources = discoverRoms();
  return {
    note: "Generated by `npm run build:roms -- --write-manifest`. Every ROM rebuilds byte-identically from source.",
    toolchain: { node: process.versions.node },
    roms: Object.fromEntries(Object.keys(roms).sort().map(n => [n, { source: sources.find(s => s.name === n)!.file.replace(/\\/g, "/"), bytes: roms[n].length, sha256: sha256(roms[n]) }])),
  };
}

if (isCliEntry(import.meta.url)) {
  if (discoverRoms().some(s => s.lang === "scrim")) await loadScrim();
  const roms = buildAll();
  for (const [name, rom] of Object.entries(roms)) {
    const out = join("build/roms", `${name}.rom`);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, rom);
  }
  const manifest = manifestOf(roms);
  if (process.argv.includes("--write-manifest")) writeFileSync("roms/manifest.json", JSON.stringify(manifest, null, 2) + "\n");
  console.log(`built ${Object.keys(roms).length} ROMs into build/roms`);
}
